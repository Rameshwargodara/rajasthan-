for (const ex of paragraphs15to40) {
  // Normalize internal whitespace to single spaces, trim ends
  const cleanHindi = ex.hindi.replace(/\r?\n/g, ' ').replace(/\s+/g, ' ').trim();
  const krutiContent = unicodeToKruti(cleanHindi);

  const fullObj = {
    id: ex.id,
    title: ex.title,
    category: ex.category,
    focusKeys: 'Complete KrutiDev Keyboard',
    focusHindi: cleanHindi,
    description: cleanHindi.substring(0, 65) + '...',
    content: krutiContent
  };

  const existingIdx = allParagraphs.findIndex(p => p.id === ex.id);
  if (existingIdx !== -1) {
    allParagraphs[existingIdx] = fullObj;
  } else {
    allParagraphs.push(fullObj);
  }
}

// Ensure proper sorting by id
allParagraphs.sort((a, b) => a.id - b.id);

fs.writeFileSync(paragraphs50Path, JSON.stringify(allParagraphs, null, 2), 'utf8');

