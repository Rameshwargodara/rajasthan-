const lessonsFile = path.join(__dirname, '../src/data/hindiLessons.ts');
let fullTs = fs.readFileSync(lessonsFile, 'utf8');

// Load current 50 lessons from paragraphs_50.json if exists or update
const paragraphs50Path = path.join(__dirname, 'paragraphs_50.json');
let allParagraphs = [];
if (fs.existsSync(paragraphs50Path)) {
  allParagraphs = JSON.parse(fs.readFileSync(paragraphs50Path, 'utf8'));
}

// Replace the first 10
for (const ex of exercises1to10) {
  const krutiContent = unicodeToKruti(ex.hindi);
  const fullObj = {
    id: ex.id,
    title: `Exercise : ${ex.id}/50`,
    category: ex.category,
    focusKeys: 'Complete KrutiDev Keyboard',
    focusHindi: ex.hindi,
    description: ex.description,
    content: krutiContent
  };
  
  const existingIdx = allParagraphs.findIndex(p => p.id === ex.id);
  if (existingIdx !== -1) {
    allParagraphs[existingIdx] = fullObj;
  } else {
    allParagraphs.push(fullObj);
  }
}

// Re-convert exercises 11 to 50 with the fixed converter to ensure 100% typability across all exercises
for (let i = 10; i < allParagraphs.length; i++) {
  allParagraphs[i].title = `Exercise : ${allParagraphs[i].id}/50`;
  allParagraphs[i].content = unicodeToKruti(allParagraphs[i].focusHindi);
}

fs.writeFileSync(paragraphs50Path, JSON.stringify(allParagraphs, null, 2), 'utf8');

const escapeStr = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

let tsEntries = allParagraphs.map(p => {
  return `  {
    id: ${p.id},
    title: '${escapeStr(p.title)}',
    category: '${escapeStr(p.category)}',
    focusKeys: '${escapeStr(p.focusKeys)}',
    focusHindi:
      '${escapeStr(p.focusHindi)}',
    description: '${escapeStr(p.description)}',
    content:
      '${escapeStr(p.content)}',
  }`;
}).join(',\n');

const replacementBlock = `// Type Paragraphs Exercises (1 to 50) - Full passage typing tests
export const HINDI_TYPE_PARAGRAPH_LESSONS: HindiLesson[] = [
${tsEntries}
];
`;

const marker = '// Type Paragraphs Exercises (1 to 50) - Full passage typing tests';
const splitIndex = fullTs.indexOf(marker);

if (splitIndex === -1) {
  console.error('Marker not found in hindiLessons.ts!');
  process.exit(1);
}

const newContent = fullTs.substring(0, splitIndex) + replacementBlock;
fs.writeFileSync(lessonsFile, newContent, 'utf8');
console.log('Successfully updated Exercises 1 to 50 with 100% accurate, typable KrutiDev in src/data/hindiLessons.ts!');
